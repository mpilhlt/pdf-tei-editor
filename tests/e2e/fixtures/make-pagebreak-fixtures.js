#!/usr/bin/env node
/**
 * Generates the page break fixtures of the "standard" E2E fixture set: two
 * small text PDFs with matching TEI documents that mark the page starts with
 * `<pb/>`, for testing the synchronization of the XML editor with the PDF
 * viewer ("Sync with editor" switch, app/src/plugins/editor-sync.js).
 *
 * - `pagebreaks-n`: 4 PDF pages; page 1 is a cover page without `<pb/>`, pages
 *   2-4 start with `<pb n="2"/>` .. `<pb n="4"/>`. The `n` attribute gives the
 *   PDF page, the position among the `<pb/>` elements does not.
 * - `pagebreaks-ordinal`: 3 PDF pages, each starting with a `<pb/>` without
 *   `n`. The position among the `<pb/>` elements gives the PDF page.
 *
 * The output is committed; re-run only after changing this script:
 *
 *     node tests/e2e/fixtures/make-pagebreak-fixtures.js
 */

import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const FILES_DIR = join(dirname(fileURLToPath(import.meta.url)), 'standard', 'files');

/** Pseudo-random but fixed vocabulary, so that every page has distinct text */
const WORDS = ['archive', 'statute', 'river', 'lantern', 'harvest', 'mirror', 'treaty', 'garden',
  'compass', 'quarry', 'violin', 'meadow', 'harbor', 'ledger', 'falcon', 'orchard', 'canyon',
  'beacon', 'thimble', 'glacier', 'saddle', 'tavern', 'pigment', 'oyster'];

/**
 * Returns the paragraphs of a page: 6 paragraphs of 3 lines, each line of 7 words, so
 * that the XML editor can be scrolled.
 * @param {number} seed - Seed of the word sequence
 * @returns {string[][]} Paragraphs as lists of lines
 */
function pageParagraphs(seed) {
  let state = seed * 7919 + 17;
  const next = () => (state = (state * 1103515245 + 12345) % 2147483648);
  return Array.from({ length: 6 }, () =>
    Array.from({ length: 3 }, () =>
      Array.from({ length: 7 }, () => WORDS[Math.floor(next() / 65536) % WORDS.length]).join(' ')));
}

/**
 * Escapes a string for a PDF literal string.
 * @param {string} s
 * @returns {string}
 */
function pdfString(s) {
  return s.replace(/[\\()]/g, c => '\\' + c);
}

/**
 * Builds a PDF with one Helvetica text block per page.
 * @param {string[][]} pages - Lines of text per page
 * @returns {Buffer}
 */
function buildPdf(pages) {
  /** @type {string[]} */
  const objects = [];
  const pageCount = pages.length;
  // 1: catalog, 2: pages, 3: font, then per page: page object, content stream
  const pageIds = pages.map((_, i) => 4 + i * 2);
  objects[1] = '<< /Type /Catalog /Pages 2 0 R >>';
  objects[2] = `<< /Type /Pages /Kids [${pageIds.map(id => `${id} 0 R`).join(' ')}] /Count ${pageCount} >>`;
  objects[3] = '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>';
  pages.forEach((lines, i) => {
    const content = ['BT', '/F1 12 Tf', '16 TL', '72 760 Td',
      ...lines.map(line => `(${pdfString(line)}) Tj T*`), 'ET'].join('\n');
    objects[pageIds[i]] = `<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 3 0 R >> >> /Contents ${pageIds[i] + 1} 0 R >>`;
    objects[pageIds[i] + 1] = `<< /Length ${Buffer.byteLength(content)} >>\nstream\n${content}\nendstream`;
  });

  let pdf = '%PDF-1.4\n';
  /** @type {number[]} */
  const offsets = [];
  for (let id = 1; id < objects.length; id++) {
    offsets[id] = Buffer.byteLength(pdf);
    pdf += `${id} 0 obj\n${objects[id]}\nendobj\n`;
  }
  const xrefOffset = Buffer.byteLength(pdf);
  pdf += `xref\n0 ${objects.length}\n0000000000 65535 f \n`;
  for (let id = 1; id < objects.length; id++) {
    pdf += `${String(offsets[id]).padStart(10, '0')} 00000 n \n`;
  }
  pdf += `trailer\n<< /Size ${objects.length} /Root 1 0 R >>\nstartxref\n${xrefOffset}\n%%EOF\n`;
  return Buffer.from(pdf, 'latin1');
}

/**
 * Escapes a string for XML text content.
 * @param {string} s
 * @returns {string}
 */
function xmlText(s) {
  return s.replace(/&/g, '&amp;').replace(/</g, '&lt;');
}

/**
 * Builds the TEI document of a fixture.
 * @param {string} title
 * @param {Array<{pb: string|null, heading: string, paragraphs: string[][]}>} pages -
 *   `pb` is the `<pb/>` element that starts the page, or null for none
 * @returns {string}
 */
function buildTei(title, pages) {
  const body = pages.map(({ pb, heading, paragraphs }) => [
    pb ? `      ${pb}` : null,
    `      <head>${xmlText(heading)}</head>`,
    ...paragraphs.map(lines => `      <p>${xmlText(lines.join(' '))}</p>`)
  ].filter(Boolean).join('\n')).join('\n');
  return `<?xml version="1.0" encoding="UTF-8"?>
<TEI xmlns="http://www.tei-c.org/ns/1.0">
  <teiHeader>
    <fileDesc>
      <titleStmt>
        <title level="a">${xmlText(title)}</title>
      </titleStmt>
      <publicationStmt>
        <p>Test fixture, generated by tests/e2e/fixtures/make-pagebreak-fixtures.js</p>
      </publicationStmt>
      <sourceDesc>
        <p>Test fixture.</p>
      </sourceDesc>
    </fileDesc>
  </teiHeader>
  <text>
    <body>
${body}
    </body>
  </text>
</TEI>
`;
}

/**
 * Writes the PDF and the TEI document of a fixture.
 * @param {string} docId - File name stem, which pairs the PDF with the TEI document
 * @param {string} title
 * @param {Array<{pb: string|null, heading: string, seed: number}>} pageSpecs
 */
function writeFixture(docId, title, pageSpecs) {
  const pages = pageSpecs.map(({ pb, heading, seed }) => ({ pb, heading, paragraphs: pageParagraphs(seed) }));
  const pdf = buildPdf(pages.map(({ heading, paragraphs }) => [heading, '', ...paragraphs.flatMap(lines => [...lines, ''])]));
  const pdfDir = join(FILES_DIR, 'pdf', 'pagebreaks');
  const teiDir = join(FILES_DIR, 'tei', 'pagebreaks');
  mkdirSync(pdfDir, { recursive: true });
  mkdirSync(teiDir, { recursive: true });
  writeFileSync(join(pdfDir, `${docId}.pdf`), pdf);
  writeFileSync(join(teiDir, `${docId}.tei.xml`), buildTei(title, pages));
}

writeFixture('pagebreaks-n', 'Page breaks with n attribute', [
  { pb: null, heading: 'Cover page of the page break fixture', seed: 1 },
  { pb: '<pb n="2"/>', heading: 'First chapter', seed: 2 },
  { pb: '<pb n="3"/>', heading: 'Second chapter', seed: 3 },
  { pb: '<pb n="4"/>', heading: 'Third chapter', seed: 4 }
]);

writeFixture('pagebreaks-ordinal', 'Page breaks without n attribute', [
  { pb: '<pb/>', heading: 'Opening section', seed: 5 },
  { pb: '<pb/>', heading: 'Middle section', seed: 6 },
  { pb: '<pb/>', heading: 'Closing section', seed: 7 }
]);

console.log(`Fixtures written to ${FILES_DIR}/{pdf,tei}/pagebreaks/`);
